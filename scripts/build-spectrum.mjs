/**
 * Builds Spectrum 2 assets for Helix delivery under deps/spectrum/dist/.
 * - tokens.css: concatenated tokens-v2 + typography from @spectrum-web-components/styles
 * - index.js: esbuild bundle of deps/spectrum/src/index.js (sp-theme, sp-button, …)
 */
import { execSync } from 'node:child_process';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const stylesPkg = join(root, 'node_modules/@spectrum-web-components/styles');
const distDir = join(root, 'deps/spectrum/dist');

const TOKEN_PARTS = [
  'tokens-v2/light-vars.css',
  'tokens-v2/medium-vars.css',
  'tokens-v2/global-vars.css',
  'typography.css',
];

mkdirSync(distDir, { recursive: true });

let tokensCss = `/**
 * Spectrum 2 design tokens for drago-toolkit tools.
 * Generated by npm run build:spectrum — do not edit by hand.
 * @see https://opensource.adobe.com/spectrum-web-components/tools/styles/
 */
`;

for (const part of TOKEN_PARTS) {
  tokensCss += `\n/* --- ${part} --- */\n`;
  tokensCss += readFileSync(join(stylesPkg, part), 'utf8');
}

writeFileSync(join(distDir, 'tokens.css'), tokensCss);

execSync(
  'npx esbuild --format=esm --minify ./deps/spectrum/src/index.js --bundle --outfile=./deps/spectrum/dist/index.js',
  { cwd: root, stdio: 'inherit' },
);
